"""Render CHANGELOG.md's Unreleased section from merged conventional commits.

The changelog records merged source history, never a release or a runtime
fact. Only `feat`, `fix`, `docs` and `ci` subjects are listed; other types
(such as `chore`) and merge commits are not. A pull request number at the end
of a subject is rendered as a link.

The section starts after the latest annotated release tag, so an entry that
already has a released section is not rendered again. A release preparation
marker defers that tag until the preparation commit is on `main`;
`--validate-release` verifies the published state, and `--check` reports drift
between the committed section and that rendering.

Rendering fails closed when the history is shallow, when a released heading
cannot be reconciled with a local reachable annotated tag (for example in a
`--no-tags` clone), or while a release preparation marker has no tag yet.

Standard library only, no network:

    python3 scripts/render_changelog.py                  # print the section
    python3 scripts/render_changelog.py --write          # replace it
    python3 scripts/render_changelog.py --check          # report drift
    python3 scripts/render_changelog.py --validate-release
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
CHANGELOG = ROOT / "CHANGELOG.md"
REPOSITORY = "mikomiel/ci-burst"
UNRELEASED = "## [Unreleased]"
GENERATED_MARKER = "<!-- generated by scripts/render_changelog.py -->"
PROVENANCE = (
    "This changelog records merged source history. It is not deployment,\n"
    "runtime, or qualification evidence: an entry can be unreleased, and a\n"
    "merge is neither a release nor a deployment."
)

CATEGORY = {"feat": "Added", "fix": "Fixed", "docs": "Documentation", "ci": "CI"}
CATEGORY_ORDER = ("Added", "Changed", "Fixed", "Documentation", "CI")
_SUBJECT = re.compile(r"^(feat|fix|docs|ci)(?:\([^)]*\))?!?:\s+(?P<text>\S.*)$")
_PULL_REQUEST = re.compile(r"\s+\(#(?P<number>[0-9]+)\)$")
_VERSION = r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"
_RELEASE_TAG = re.compile(rf"^v(?P<version>{_VERSION})$")
# Anything a human would read as a release tag, so an invalid one can be
# rejected instead of silently ignored.
_RELEASE_SHAPED = re.compile(r"^v?[0-9]+\.[0-9]+\.[0-9]+$")
_H2 = re.compile(r"^ {0,3}##[ \t]+")
_RELEASED_HEADING = re.compile(
    rf"^## \[(?P<version>{_VERSION})\] - [0-9]{{4}}-[0-9]{{2}}-[0-9]{{2}}$"
)
_RELEASE_PENDING = re.compile(rf"<!-- release-pending: v(?P<version>{_VERSION}) -->")

HEADER = f"""# Changelog

{PROVENANCE}

The Unreleased section is generated from the Git history by
[`scripts/render_changelog.py`](scripts/render_changelog.py); do not edit it by
hand. A released section is added for an annotated semantic version tag on
`main`; [CONTRIBUTING.md](CONTRIBUTING.md#releases) owns the preparation marker
and the validation step that binds it to that tag.

{GENERATED_MARKER}
"""


class Entry(NamedTuple):
    category: str
    text: str
    pull_request: int | None


def parse_subject(subject):
    """Return an Entry for a listed conventional subject, or None."""
    match = _SUBJECT.match(subject.strip())
    if match is None:
        return None
    text = match.group("text").strip()
    pull_request = None
    pull = _PULL_REQUEST.search(text)
    if pull is not None:
        pull_request = int(pull.group("number"))
        text = text[: pull.start()].strip()
    text = text.rstrip(".").strip()
    if not text:
        return None
    return Entry(CATEGORY[match.group(1)], text[0].upper() + text[1:] + ".", pull_request)


def render_unreleased(subjects, repository=REPOSITORY):
    """Render the heading, categories and entries for the given subjects."""
    grouped = {}
    for subject in subjects:
        entry = parse_subject(subject)
        if entry is not None:
            grouped.setdefault(entry.category, []).append(entry)
    lines = [UNRELEASED, ""]
    for category in CATEGORY_ORDER:
        entries = grouped.get(category)
        if not entries:
            continue
        lines.extend([f"### {category}", ""])
        for entry in entries:
            if entry.pull_request is None:
                lines.append(f"- {entry.text}")
            else:
                url = f"https://github.com/{repository}/pull/{entry.pull_request}"
                lines.append(f"- {entry.text[:-1]} ([#{entry.pull_request}]({url})).")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def git(root, *arguments):
    return subprocess.run(
        ("git", "-C", str(root), *arguments),
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def merged_subjects(root=ROOT, since=None):
    """Subjects of non-merge commits after ``since``, oldest first; no network."""
    revision = f"{since}..HEAD" if since else "HEAD"
    output = git(root, "log", "--no-merges", "--reverse", "--format=%s", revision)
    return [line for line in output.splitlines() if line.strip()]


def tag_types(root=ROOT):
    """Tag name to object type; an annotated tag reports ``tag``."""
    output = git(root, "for-each-ref", "refs/tags", "--format=%(refname:short)%09%(objecttype)")
    found = {}
    for line in output.splitlines():
        name, _, kind = line.partition("\t")
        found[name] = kind
    return found


def is_shallow(root=ROOT):
    """True when the checkout may lack history, including when that is unknown."""
    try:
        return git(root, "rev-parse", "--is-shallow-repository").strip() == "true"
    except (subprocess.CalledProcessError, OSError):
        return True


def _reachable(name, root=ROOT):
    """True when ``name`` is an ancestor of HEAD."""
    try:
        git(root, "merge-base", "--is-ancestor", name, "HEAD")
    except subprocess.CalledProcessError:
        return False
    return True


def _tag_has_section(name, root=ROOT):
    """True when CHANGELOG.md at the tag carries the matching released heading."""
    try:
        text = git(root, "show", f"{name}:CHANGELOG.md")
    except subprocess.CalledProcessError:
        return False
    version = name[1:]
    for line in text.splitlines():
        match = _RELEASED_HEADING.match(line)
        if match is not None and match.group("version") == version:
            return True
    return False


def applicable_tags(root=ROOT):
    """Reachable annotated vX.Y.Z tags, mapped to whether their commit has the section."""
    found = {}
    for name, kind in tag_types(root).items():
        if kind != "tag" or _RELEASE_TAG.match(name) is None or not _reachable(name, root):
            continue
        found[name] = _tag_has_section(name, root)
    return found


def invalid_release_refs(root=ROOT):
    """Reachable release-shaped refs that cannot serve as a release boundary.

    ``applicable_tags`` admits only annotated ``vX.Y.Z`` tags, so without this
    the validators call a repository consistent while the renderer rejects the
    same ref: a lightweight tag, an unprefixed tag, or a leading-zero version.
    """
    found = []
    for name, kind in tag_types(root).items():
        if _RELEASE_SHAPED.match(name) is None or not _reachable(name, root):
            continue
        if kind != "tag" or _RELEASE_TAG.match(name) is None:
            found.append(name)
    return tuple(sorted(found))


def _tag_error(version):
    return (
        f"released heading [{version}] needs an annotated tag v{version} "
        "reachable from HEAD (missing, lightweight, or absent from this clone)"
    )


def release_tag(root=ROOT):
    """Latest release tag reachable from HEAD, or None when none is available.

    The boundary must be an annotated ``vMAJOR.MINOR.PATCH`` tag. A lightweight
    or unprefixed tag raises ValueError instead of being ignored, because
    ignoring it would render already-released commits again. None alone cannot
    distinguish an absent release from missing release evidence; the caller
    reconciles it with the released sections in the changelog.
    """
    try:
        name = git(
            root,
            "describe",
            "--tags",
            "--abbrev=0",
            "--match",
            "v[0-9]*",
            "--match",
            "[0-9]*",
        ).strip()
    except subprocess.CalledProcessError:
        return None
    if _RELEASE_TAG.match(name) is None or git(root, "cat-file", "-t", name).strip() != "tag":
        raise ValueError(f"release boundary {name!r} must be an annotated tag vMAJOR.MINOR.PATCH")
    return name


def released_sections(text):
    """Return version to section text for released ``## [x.y.z]`` headings.

    A bracketed H2 heading that is not canonical (``## [x.y.z]`` with exactly
    one space), a malformed version, or a duplicate version heading raises
    ValueError, so a spacing or structural defect cannot disappear from the
    section map.
    """
    sections = {}
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        heading = _H2.match(line)
        if heading is None or line == UNRELEASED:
            continue
        match = _RELEASED_HEADING.match(line)
        if match is None:
            if line[heading.end():].startswith("["):
                raise ValueError(f"noncanonical release heading: {line!r}")
            continue
        version = match.group("version")
        if version in sections:
            raise ValueError(f"duplicate release heading [{version}]")
        start = index
        while index < len(lines) and _H2.match(lines[index]) is None:
            index += 1
        sections[version] = "\n".join(lines[start:index]).strip()
    return sections


def _pending(sections):
    return [
        version
        for version, section in sections.items()
        if _RELEASE_PENDING.search(section)
    ]


def pending_versions(text):
    """Release versions whose section carries a preparation marker."""
    return _pending(released_sections(text))


def _reconcile(text, tags, allow_preparation, invalid=()):
    """Reconcile released sections and applicable tags in both directions.

    ``tags`` maps tag names from :func:`applicable_tags` to whether
    ``CHANGELOG.md`` at that tag contains the matching section. A
    preparation-marked section may lack its tag only when the caller allows
    preparation; every applicable tag still needs its section.
    """
    try:
        sections = released_sections(text)
    except ValueError as error:
        return [str(error)]
    errors = [
        f"release tag {name} must be an annotated vMAJOR.MINOR.PATCH tag reachable from HEAD"
        for name in invalid
    ]
    pending = _pending(sections)
    if len(pending) > 1:
        errors.append(
            "more than one release is marked pending: "
            + ", ".join(f"v{version}" for version in pending)
        )
    inside = sum(len(_RELEASE_PENDING.findall(section)) for section in sections.values())
    if len(_RELEASE_PENDING.findall(text)) > inside:
        errors.append("release-pending marker outside a released section")
    for version, section in sections.items():
        marker = _RELEASE_PENDING.search(section)
        if marker is not None:
            if marker.group("version") != version:
                errors.append(
                    f"release-pending marker v{marker.group('version')} "
                    f"does not match heading [{version}]"
                )
            if not allow_preparation:
                errors.append(
                    f"release-pending marker for v{version} remains; "
                    "remove it after creating the tag"
                )
            # The marker waives only tag *absence*: a tag that exists but
            # predates the section still fails closed.
            if f"v{version}" in tags and not tags[f"v{version}"]:
                errors.append(
                    f"annotated tag v{version} does not contain the released section [{version}]"
                )
            continue
        if f"v{version}" not in tags:
            errors.append(_tag_error(version))
        elif not tags[f"v{version}"]:
            errors.append(
                f"annotated tag v{version} does not contain the released section [{version}]"
            )
    for name in tags:
        if name[1:] not in sections:
            errors.append(
                f"annotated tag {name} has no released section; "
                "released history is not reconciled"
            )
    return errors


def binding_errors(text, tags, invalid=()):
    """Pre-merge errors: sections and tags reconcile, preparation is explicit."""
    return _reconcile(text, tags, allow_preparation=True, invalid=invalid)


def release_validation_errors(text, tags, invalid=()):
    """Published-state errors: no marker, and sections and tags reconcile."""
    return _reconcile(text, tags, allow_preparation=False, invalid=invalid)


def boundary_problem(text, root=ROOT):
    """Reason the Unreleased boundary cannot be trusted, or None.

    A shallow checkout cannot render complete history, and a section or tag
    that fails bidirectional reconciliation cannot establish where Unreleased
    starts.
    """
    if is_shallow(root):
        return (
            "shallow history cannot establish the release boundary; "
            "run git fetch --unshallow"
        )
    errors = _reconcile(
        text, applicable_tags(root), allow_preparation=True, invalid=invalid_release_refs(root)
    )
    return errors[0] if errors else None


def write_blocked(text, boundary):
    """Reason why rendering must not run, or None when the boundary is settled."""
    try:
        pending = pending_versions(text)
    except ValueError as error:
        return str(error)
    if not pending:
        return None
    if len(pending) == 1 and boundary == f"v{pending[0]}":
        return None
    versions = ", ".join(f"v{version}" for version in pending)
    return (
        f"release preparation for {versions} is pending; "
        "create the annotated tag and remove the marker before regenerating"
    )


def _section_bounds(lines):
    try:
        start = lines.index(UNRELEASED)
    except ValueError:
        return None
    for index in range(start + 1, len(lines)):
        if _H2.match(lines[index]) is not None:
            return start, index
    return start, len(lines)


def unreleased_section(text):
    """Return the current Unreleased section, or None when it is absent."""
    lines = text.splitlines()
    bounds = _section_bounds(lines)
    if bounds is None:
        return None
    start, end = bounds
    return "\n".join(lines[start:end]).rstrip("\n") + "\n"


def replace_unreleased(text, section):
    """Replace the Unreleased section and keep any released sections intact."""
    lines = text.splitlines()
    bounds = _section_bounds(lines)
    if bounds is None:
        return text.rstrip("\n") + "\n\n" + section.rstrip("\n") + "\n"
    start, end = bounds
    updated = lines[:start] + section.rstrip("\n").splitlines() + [""] + lines[end:]
    return "\n".join(updated).rstrip("\n") + "\n"


def unreleased_is_current(text, section):
    """True when the committed Unreleased region already equals ``section``.

    The region is compared exactly, not through :func:`unreleased_section`,
    which trims blank lines before the next heading and repairs a missing final
    newline. It runs from the ``## [Unreleased]`` heading to the next level-two
    heading, or to the end of the file, and :func:`replace_unreleased` always
    separates it from that heading with exactly one blank line. A surplus blank
    line or a missing final newline is therefore drift, not formatting that can
    be normalised away.
    """
    lines = text.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    start = next(
        (index for index, line in enumerate(lines) if line.rstrip("\r\n") == UNRELEASED),
        None,
    )
    if start is None:
        return False
    end = next(
        (index for index in range(start + 1, len(lines)) if _H2.match(lines[index])),
        None,
    )
    if end is None:
        return text[offsets[start]:] == section
    return text[offsets[start]:offsets[end]] == section + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    actions = parser.add_mutually_exclusive_group()
    actions.add_argument(
        "--write",
        action="store_true",
        help="replace the Unreleased section in CHANGELOG.md instead of printing it",
    )
    actions.add_argument(
        "--validate-release",
        action="store_true",
        help="require every released heading to have an annotated tag and no preparation marker",
    )
    actions.add_argument(
        "--check",
        action="store_true",
        help="report a committed Unreleased section that differs from the rendering and exit 1",
    )
    args = parser.parse_args(argv)

    text = CHANGELOG.read_text(encoding="utf-8") if CHANGELOG.exists() else HEADER + "\n"

    if args.validate_release:
        errors = release_validation_errors(
            text, applicable_tags(), invalid_release_refs()
        )
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        if errors:
            return 1
        print("release state is consistent")
        return 0

    problem = boundary_problem(text)
    if problem is not None:
        print(f"error: {problem}", file=sys.stderr)
        return 1
    try:
        boundary = release_tag()
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    blocked = write_blocked(text, boundary)
    if blocked is not None:
        print(f"error: {blocked}", file=sys.stderr)
        return 1
    section = render_unreleased(merged_subjects(since=boundary))
    if args.check:
        if unreleased_is_current(text, section):
            print("changelog is up to date")
            return 0
        sys.stdout.write(section)
        print(
            "error: the committed Unreleased section is stale; regenerate it "
            "with python3 scripts/render_changelog.py --write",
            file=sys.stderr,
        )
        return 1
    if not args.write:
        sys.stdout.write(section)
        return 0
    CHANGELOG.write_text(replace_unreleased(text, section), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
